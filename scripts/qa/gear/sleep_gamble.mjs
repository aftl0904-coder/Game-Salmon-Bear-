import { chromium } from 'playwright'
const OUT = '/tmp/res2x-on58/docs/qa-gear'
const b = await chromium.launch({ args: ['--use-gl=swiftshader', '--enable-unsafe-swiftshader'] })
const ctx = await b.newContext({ viewport: { width: 1280, height: 720 } })
await ctx.addInitScript(() => { localStorage.setItem('sake-kuma-difficulty-v1', 'normal'); localStorage.setItem('sake-kuma-progress-v1', JSON.stringify({ maxStage: 5 })) })
const page = await ctx.newPage()
const errs = []; page.on('pageerror', (e) => errs.push(e.message)); page.on('console', (m) => { if (m.type() === 'error') errs.push(m.text().slice(0, 160)) })
await page.goto('http://127.0.0.1:47313/'); await page.waitForTimeout(5000)
await page.evaluate(() => { const g = window.__SAKE_GAME__; g.registry.set('stageNo', 2); g.registry.set('difficulty', 'normal'); g.registry.set('playMode', '1p'); g.registry.set('soloCast', 'girl'); g.registry.set('stageRound', 1); g.registry.set('carryPurse', { boy: 0, girl: 60 }); g.registry.set('carryCoins', 60); for (const s of g.scene.getScenes(true)) g.scene.stop(s.scene.key); g.scene.start('play') })
await page.waitForTimeout(3000)
for (let i = 0; i < 10; i++) { const intro = await page.evaluate(() => !!window.__SAKE_GAME__.scene.getScene('play').storyIntro); if (!intro) break; await page.keyboard.press('Enter'); await page.waitForTimeout(700) }
const st = () => page.evaluate(() => { const s = window.__SAKE_GAME__.scene.getScene('play'); return { hp: s.boy.hp, coins: s.purse.girl, stock: s.coinStock, modal: s.clearModal, sel: s.clearBtns.map((b, i) => `${b.id}:${b.on ? 1 : 0}${i === s.clearSel ? '*' : ''}`).join(' '), status: s.clearStatus?.text, win: !!s.registry.get('winScreenShown'), stage: s.registry.get('stageNo') } })
await page.evaluate(() => { const s = window.__SAKE_GAME__.scene.getScene('play'); s.boy.hp = 2; s.win() })
await page.waitForTimeout(5500)
console.log('1 card', JSON.stringify(await st()))
await page.screenshot({ path: `${OUT}/clear-card.png` })
const key = async (k) => { await page.keyboard.press(k); await page.waitForTimeout(350) }
await key('ArrowLeft'); await key('ArrowLeft')
console.log('2 sel sleep', (await st()).sel)
await key('Enter')
console.log('3 confirm open', JSON.stringify(await st()))
await page.screenshot({ path: `${OUT}/sleep-confirm.png` })
await key('Enter')
await page.waitForTimeout(400)
console.log('4 after sleep', JSON.stringify(await st()))
await page.screenshot({ path: `${OUT}/after-sleep.png` })
await page.waitForTimeout(500)
console.log('4b modal released', (await st()).modal)
console.log('5 sel gamble', (await st()).sel)
await key('Enter')
await page.screenshot({ path: `${OUT}/gamble-open.png` })
await page.evaluate(() => { window.__r = Math.random; Math.random = () => 0.1; setTimeout(() => (Math.random = window.__r), 30) })
await key('Enter')
await page.waitForTimeout(4500)
await page.screenshot({ path: `${OUT}/gamble-win.png` })
console.log('6 after win', JSON.stringify(await st()))
await page.evaluate(() => { Math.random = () => 0.9; setTimeout(() => (Math.random = window.__r), 30) })
await key('Enter')
await page.waitForTimeout(4500)
await page.screenshot({ path: `${OUT}/gamble-lose.png` })
console.log('7 after lose', JSON.stringify(await st()))
await key('Escape')
await page.waitForTimeout(500)
console.log('8 closed', JSON.stringify(await st()))
await page.screenshot({ path: `${OUT}/clear-after-gamble.png` })
// broke case: 10 coins left?
console.log('errors', errs)
await b.close()
