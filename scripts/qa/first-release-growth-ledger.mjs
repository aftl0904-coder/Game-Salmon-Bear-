// Pure model tests only: not integrated with the game, storage or UI.
import assert from 'node:assert/strict'
import fs from 'node:fs'
import ts from 'typescript'
const source = fs.readFileSync('src/game/growth.ts', 'utf8')
const js = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText
const g = await import(`data:text/javascript;base64,${Buffer.from(js).toString('base64')}`)
const a = book => book.branches.find(b => b.id === book.activeId)
const clone = x => structuredClone(x)
const cleared = (book, stage, rank = 'C', context = 'main') => g.advanceGrowthBook(book, stage, rank, context)
const earned = book => [a(book).heroes.boy.earned, a(book).heroes.girl.earned]
const alloc = (hp = 0, atk = 0, def = 0, stam = 0, sp = 0) => ({ hp, atk, def, stam, sp })
let book = g.createGrowthBook('first', 1)
assert.deepEqual(earned(book), [5, 5]); assert.equal(a(book).nextStage, 1)
book = g.respecGrowthBook(book, 'boy', alloc(1, 2, 1, 1, 0))
assert.equal(g.unspentGrowth(a(book).heroes.boy), 0)
assert.equal(g.unspentGrowth(a(book).heroes.girl), 5)
assert.throws(() => g.respecGrowthBook(book, 'boy', alloc(6)), RangeError)
assert.throws(() => g.respecGrowthBook(book, 'girl', alloc(-1)), RangeError)
assert.throws(() => g.respecGrowthBook(book, 'other', alloc()), RangeError)
const before = clone(book)
book = cleared(book, 1); book = cleared(book, 2); book = cleared(book, 3, 'S')
assert.deepEqual(earned(book), [8, 8]); assert.equal(a(book).awards['3'], 'S')
for (let i = 0; i < 1000; i++) book = cleared(book, 3, 'S')
assert.deepEqual(earned(book), [8, 8]); assert.equal(a(book).nextStage, 4)
assert.deepEqual(cleared(book, 5, 'S', 'side'), book)
assert.throws(() => cleared(book, 5, 'S'), RangeError)
assert.deepEqual(before.branches[0].heroes.boy.allocation, alloc(1, 2, 1, 1, 0), 'inputs remain independent')
book = cleared(book, 4); book = cleared(book, 5, 'A')
assert.deepEqual(earned(book), [10, 10])
const old = clone(a(book))
let fresh = g.startGrowthBranch(book, 'fresh', 1, null)
assert.equal(fresh.carriedOldGrowth, false); book = fresh.book
assert.deepEqual(earned(book), [5, 5]); assert.deepEqual(book.branches[0], old)
book = cleared(book, 1); book = cleared(book, 2); book = cleared(book, 3, 'B')
assert.deepEqual(earned(book), [6, 6]); assert.deepEqual(book.branches[0], old)
const restored = g.startGrowthBranch(book, 'carry-old', 6, 'first')
assert.equal(restored.carriedOldGrowth, true); book = restored.book
assert.deepEqual(earned(book), [10, 10], 'carry 10 stays 10, not 15 or 16')
assert.deepEqual(a(book).heroes.boy.allocation, old.heroes.boy.allocation)
assert.deepEqual(book.branches[1].heroes.boy.earned, 6, 'no merge and archive survives')
book = cleared(book, 6); book = cleared(book, 7, 'S')
assert.deepEqual(earned(book), [13, 13]); assert.equal(a(book).awards['7'], 'S')
book = cleared(book, 7, 'S'); assert.deepEqual(earned(book), [13, 13])
book = g.respecGrowthBook(book, 'girl', alloc(0, 0, 0, 0, 13))
assert.deepEqual(earned(book), [13, 13]); assert.equal(a(book).heroes.boy.allocation.sp, 0)
for (const [rank, points] of Object.entries({ S: 3, A: 2, B: 1, C: 0 })) {
  let b = g.createGrowthBook(`rank-${rank}`, 6)
  b = cleared(b, 6); b = cleared(b, 7, rank)
  assert.deepEqual(earned(b), [5 + points, 5 + points]); assert.equal(a(b).awards['7'], rank)
  assert.deepEqual(cleared(b, 7, 'S'), b, `repeated ${rank} cannot be upgraded`)
}
for (const stage of [3, 5, 7]) for (const [rank, points] of Object.entries({ S: 3, A: 2, B: 1, C: 0 })) {
  let b = g.createGrowthBook(`matrix-${stage}-${rank}`, 1)
  for (let i = 1; i < stage; i++) b = cleared(b, i, 'C')
  b = cleared(b, stage, rank)
  assert.deepEqual(earned(b), [5 + points, 5 + points])
  assert.equal(a(b).awards[String(stage)], rank)
  assert.deepEqual(cleared(b, stage, 'S'), b)
}
const legacy = g.migrateEmptyLegacyGrowth('legacy', 1, 4, {})
assert.deepEqual(earned(legacy), [0, 0]); assert.deepEqual(a(legacy).awards, {})
assert.deepEqual(earned(cleared(cleared(legacy, 4), 5, 'B')), [1, 1])
const carryZero = g.startGrowthBranch(legacy, 'carry-zero', 1, 'legacy')
assert.equal(carryZero.carriedOldGrowth, false); assert.deepEqual(earned(carryZero.book), [5, 5])
assert.throws(() => g.migrateEmptyLegacyGrowth('unknown', 1, 2, { hp: 5 }), RangeError)
assert.throws(() => g.migrateEmptyLegacyGrowth('unknown', 1, 2, null), RangeError)
assert.throws(() => g.startGrowthBranch(book, 'another', 1, 'missing'), RangeError)
assert.throws(() => g.startGrowthBranch(book, 'first', 1, null), RangeError)
const tamper = f => { const b = clone(book); f(b); assert.equal(g.isGrowthBook(b), false); assert.throws(() => g.respecGrowthBook(b, 'boy', alloc()), RangeError) }
tamper(b => { b.version = 2 })
tamper(b => { b.futureField = true })
tamper(b => { b.activeId = 'first' })
tamper(b => { b.branches[1].id = 'first' })
tamper(b => { b.branches[2].sourceId = 'missing' })
tamper(b => { b.branches[0].heroes.boy.earned++ })
tamper(b => { b.branches[0].heroes.boy.allocation.hp = -1 })
tamper(b => { delete b.branches[0].awards['3'] })
tamper(b => { b.branches[2].awards['7'] = 'invalid' })
tamper(b => { b.branches[2].seed.boy++ })
tamper(b => { b.branches[0].rewardFrom = 4 })
tamper(b => { b.branches[2].awards['9'] = 'S' })
assert.equal(g.isGrowthBook(book), true)
console.log('PASS isolated growth book: 5 each, no-carry, 10-point carry/restore without merging, separate archives, side isolation, sequential S/A/B/C awards to both heroes, 1000 duplicate clears, respec conservation, legacy empty-only and corruption rejection')
console.log('NOT TESTED: runtime, actual storage/write failure, leaderboard, combat, death, UI, human play or real phone')
