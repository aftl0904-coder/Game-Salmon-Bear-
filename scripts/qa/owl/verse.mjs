import { chromium } from 'playwright'
const b = await chromium.launch({ args: ['--use-gl=swiftshader', '--enable-unsafe-swiftshader'] })
const ctx = await b.newContext({ viewport: { width: 1280, height: 720 } })
await ctx.addInitScript(() => localStorage.setItem('sake-kuma-progress-v1', JSON.stringify({ maxStage: 5 })))
const page = await ctx.newPage(); const errs = []; page.on('pageerror', (e) => errs.push(e.message))
await page.goto('http://127.0.0.1:47313/'); await page.waitForTimeout(5000)
const act = () => page.evaluate(() => window.__SAKE_GAME__.scene.getScenes(true).map((s) => s.scene.key).join(','))
const start = (data) => page.evaluate((d) => { const g = window.__SAKE_GAME__; g.registry.set('playMode', '1p'); g.registry.set('soloCast', 'boy'); for (const s of g.scene.getScenes(true)) g.scene.stop(s.scene.key); g.scene.start('worldmap', d) }, data)
await start({ from: 2, to: 3, next: 'bike', stageNo: 3, pick: true })
await page.waitForTimeout(2500)
await page.screenshot({ path: '/opt/cursor/artifacts/owl/verse-pick-3.png' })
await page.keyboard.press('ArrowRight'); await page.waitForTimeout(300)
await page.screenshot({ path: '/opt/cursor/artifacts/owl/verse-pick-4.png' })
await page.keyboard.press('Enter'); const t0 = Date.now()
await page.waitForTimeout(500)
await page.screenshot({ path: '/opt/cursor/artifacts/owl/verse-confirmed.png' })
// travel should not start until verse ends / key
const mid = await page.evaluate(() => { const s = window.__SAKE_GAME__.scene.getScene('worldmap'); return { walking: s.walking, verseGo: !!s.verseGo } })
await page.waitForTimeout(3500)
const after = await page.evaluate(() => { const s = window.__SAKE_GAME__.scene.getScene('worldmap'); return s ? { walking: s.walking, verseGo: !!s.verseGo, leaving: s.leaving } : 'gone' })
console.log('0.5s after confirm', mid, '| 4s after', after)
// Enter skips verse
await start({ from: 2, to: 3, next: 'play', stageNo: 3, pick: true }); await page.waitForTimeout(2000)
await page.keyboard.press('Enter'); await page.waitForTimeout(300)
const k1 = await page.evaluate(() => { const s = window.__SAKE_GAME__.scene.getScene('worldmap'); return { walking: s.walking, verseGo: !!s.verseGo } })
await page.keyboard.press('Enter'); await page.waitForTimeout(400)
const k2 = await page.evaluate(() => { const s = window.__SAKE_GAME__.scene.getScene('worldmap'); return { walking: s.walking, verseGo: !!s.verseGo } })
console.log('after first Enter', k1, 'after second Enter (skip verse)', k2)
// non-pick (credits has no verse)
await start({ from: 5, to: 5, next: 'credits' }); await page.waitForTimeout(800)
console.log('credits path verse visible:', await page.evaluate(() => window.__SAKE_GAME__.scene.getScene('worldmap').versePanel.visible))
console.log(errs); await b.close()
